const LEGACY_ALIASES: Record<string, string> = {
    size_38: 'woman_s',
    size_40: 'woman_m',
    size_42: 'woman_l',
};

export function getProfilesByCategory(category: ReferenceDemographic): ReferenceProfile[] {
    switch (category) {
        case 'woman': return WOMAN_PROFILES;
        case 'man': return MAN_PROFILES;
        case 'girl': return GIRL_PROFILES;
        case 'boy': return BOY_PROFILES;
        default: return [];
    }
}

export function findReferenceProfile(code: string): ReferenceProfile | undefined {
    const resolvedCode = LEGACY_ALIASES[code] || code;
    return ALL_REFERENCE_PROFILES.find((p) => p.code === resolvedCode);
}

