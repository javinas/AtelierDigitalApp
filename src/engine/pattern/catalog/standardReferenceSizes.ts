// Diccionario agrupado de todas las tallas
export const ALL_STANDARD_SIZES: Record<StandardCategoryKey, Record<string, StandardSizeEntry>> = {
    woman: WOMAN_SIZES,
    man: MAN_SIZES,
    girl: GIRL_SIZES,
    boy: BOY_SIZES,
    baby: BABY_SIZES,
};

/**
 * Consulta la entrada de talla estándar por categoría y código de talla.
 */
export function getStandardSizeEntry(categoryKey: StandardCategoryKey, size: string): StandardSizeEntry | null {
    const cat = ALL_STANDARD_SIZES[categoryKey];
    if (!cat) return null;
    return cat[size] || null;
}

/**
 * Retorna las tallas disponibles para una categoría dada.
 */
export function getAvailableStandardSizes(categoryKey: StandardCategoryKey): string[] {
    const def = STANDARD_CATEGORIES.find((c) => c.key === categoryKey);
    return def ? def.sizes : [];
}

/**
 * Retorna la lista de campos pertinentes a una categoría dada.
 */
export function getPertinentFieldsForCategory(categoryKey: StandardCategoryKey): StandardMeasurementField[] {
    const def = STANDARD_CATEGORIES.find((c) => c.key === categoryKey);
    if (!def) return [];
    return def.pertinentCodes
        .map((code) => STANDARD_MEASUREMENT_FIELDS[code])
        .filter(Boolean);
}

/**
 * Construye la nota de trazabilidad inmutable que se persistirá en la sesión cuando
 * se utilice una talla estándar como punto de partida.
 */
export function buildStandardTraceabilityNote(
    categoryKey: StandardCategoryKey,
    size: string,
    baseMeasurementsCm: Record<string, number>,
    usedAtISO: string = new Date().toISOString()
): string {
    const catDef = STANDARD_CATEGORIES.find((c) => c.key === categoryKey);
    const catLabel = catDef ? `${catDef.icon} ${catDef.label}` : categoryKey;
    const sizeEntry = getStandardSizeEntry(categoryKey, size);

    const valuesSummary = Object.entries(baseMeasurementsCm)
        .map(([k, v]) => `${k}: ${v} cm`)
        .join(', ');

    return `[TRAZABILIDAD DE MEDIDAS ESTÁNDAR]
Categoría: ${catLabel}
Talla: ${size} (${sizeEntry?.equivalency || 'Referencia estándar'})
Fuente de Referencia: ${STANDARD_SOURCE_REFERENCE}
Fecha de Utilización: ${usedAtISO}
Aviso Metodológico: ${STANDARD_SOURCE_DISCLAIMER}
Valores Base Originales (cm): ${valuesSummary}`;
}
